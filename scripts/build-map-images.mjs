// Self-hosts the map's marker photos: each image is downloaded once and saved as two small WebP files,
//   public/map/img/{key}-s.webp  128×128 (map pins, list rows)
//   public/map/img/{key}-l.webp  640 px wide (preview card)
// and lib/map/local-images.ts lists the keys so lib/map/thumb.ts serves these instead of hot-linking
// Wikimedia (≈1 s per photo) or running them through the image optimiser.
//
// Reads the markers from the running site's homepage. Re-running skips images already saved.
//   node scripts/build-map-images.mjs [http://localhost:3000/]
import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = process.cwd();
const OUT = path.join(ROOT, "public", "map", "img");
const LIST = path.join(ROOT, "lib", "map", "local-images.ts");
const UA = "RajasthanPlacesMapBuilder/1.0 (build script)";
const SITE = process.argv.find((a) => a.startsWith("http")) || "http://localhost:3000/";

/** Same as imageKey() in lib/map/thumb.ts (FNV-1a, base 36). */
function imageKey(url) {
    let h = 0x811c9dc5;
    for (let i = 0; i < url.length; i++) {
        h ^= url.charCodeAt(i);
        h = Math.imul(h, 0x01000193) >>> 0;
    }
    return h.toString(36);
}

/** A ~960 px source to download (Wikimedia: its pre-rendered thumbnail, not the original). */
function sourceUrl(url) {
    if (url.startsWith("/")) return null; // local file, read from public/
    const u = new URL(url);
    if (u.hostname === "upload.wikimedia.org" || u.hostname === "thumb.wikimedia.org") {
        const p = u.pathname;
        if (/\/thumb\//.test(p) && /\/\d+px-[^/]+$/.test(p)) return `${u.origin}${p.replace(/\/\d+px-([^/]+)$/, "/960px-$1")}`;
        const m = p.match(/^(\/wikipedia\/[^/]+)\/([0-9a-f])\/([0-9a-f]{2})\/([^/]+\.(?:jpe?g|png|webp))$/i);
        if (m) return `${u.origin}${m[1]}/thumb/${m[2]}/${m[3]}/${m[4]}/960px-${m[4]}`;
    }
    return url;
}

async function download(url) {
    for (let i = 0; i < 5; i++) {
        try {
            const res = await fetch(url, { headers: { "User-Agent": UA }, signal: AbortSignal.timeout(60000) });
            if (res.ok) return Buffer.from(await res.arrayBuffer());
            if (res.status === 404) return null;
            if (res.status === 429) await new Promise((r) => setTimeout(r, Number(res.headers.get("retry-after") || 20) * 1000));
        } catch {
            // retry
        }
        await new Promise((r) => setTimeout(r, 3000 * (i + 1)));
    }
    return null;
}

// Marker images from the homepage payload
const html = (await (await fetch(SITE)).text()).replace(/\\"/g, '"');
const urls = new Set();
for (const m of html.matchAll(/"id":"[^"]+","mode":"\w+"[^{}]*?"image":"([^"]+)"/g)) urls.add(m[1].replace(/\\u0026/g, "&"));
if (!urls.size) throw new Error(`no marker images found at ${SITE} — is the site running?`);
console.log(`${urls.size} images`);

await fs.mkdir(OUT, { recursive: true });
const saved = [];
const failed = [];
const queue = [...urls];
async function worker() {
    while (queue.length) {
        const url = queue.shift();
        const key = imageKey(url);
        const small = path.join(OUT, `${key}-s.webp`);
        const large = path.join(OUT, `${key}-l.webp`);
        try {
            await fs.access(small);
            await fs.access(large);
            saved.push(key);
            continue;
        } catch {
            // build it
        }
        const src = sourceUrl(url);
        const buf = src ? await download(src) : await fs.readFile(path.join(ROOT, "public", url)).catch(() => null);
        if (!buf) {
            failed.push(url);
            continue;
        }
        try {
            const img = sharp(buf).rotate();
            await img.clone().resize(128, 128, { fit: "cover" }).webp({ quality: 70 }).toFile(small);
            await img.clone().resize({ width: 640, withoutEnlargement: true }).webp({ quality: 72 }).toFile(large);
            saved.push(key);
            console.log(`${saved.length}/${urls.size}`);
        } catch (e) {
            failed.push(`${url} (${e.message})`);
        }
        await new Promise((r) => setTimeout(r, 250));
    }
}
await Promise.all([worker(), worker()]);

await fs.writeFile(
    LIST,
    `// Generated by scripts/build-map-images.mjs: marker photos saved under public/map/img/{key}-s|l.webp\n` +
        `export const LOCAL_IMAGES = new Set<string>(${JSON.stringify(saved.sort())});\n`
);
console.log(`saved ${saved.length}, failed ${failed.length}`);
for (const f of failed) console.log(`  failed: ${f}`);
